function Lang.new(code)
  return setmetatable({ code = (code == 'en-US') and 'en-US' or 'pt-BR' }, Lang)
end

function Lang:t(key)
  local t = STRINGS[self.code] or STRINGS['pt-BR']
  local v = t[key]
  if v ~= nil then return v end
  return (STRINGS['pt-BR'])[key] or tostring(key)
end

function Lang:cap(text)
  if self.code ~= 'en-US' then return text end
  text = tostring(text)
  local exact = CAP_EN[text]
  if exact then return exact end
  for _, p in ipairs(CAP_PATTERNS) do
    local a, b = text:match(p[1])
    if a ~= nil then return string.format(p[2], a, b) end
  end
  for _, w in ipairs(CAP_WORDS) do
    text = text:gsub('%f[%a]' .. w[1] .. '%f[%A]', w[2])
  end
  return text
end

function Lang:set(code)
  self.code = (code == 'en-US') and 'en-US' or 'pt-BR'
end

return Lang
